import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>JSON.parse(readFileSync(p,'utf8'));
const baseline=read('docs/iterations/Stage-32/evidence/stage32-matrix-production.json');
const production=read('test-results/stage33-matrix-production.json');
assert.deepEqual(production,read('test-results/stage33-matrix-second10.json'));
const changed=production.rows.flatMap((row,i)=>JSON.stringify(row)===JSON.stringify(baseline.rows[i])?[]:[{index:i,baseline:baseline.rows[i],production:row}]);
assert.equal(production.summary.naturallyConcluded,360);
assert.equal(changed.length,1);
const [{index,baseline:old,production:row}]=changed;
assert.equal(index,339);
assert.equal(row.seed,7429);
assert.equal(row.material,'steel');
assert.equal(row.size,'standard');
assert.equal(row.policy,'steer');
assert.equal(row.wave,old.wave);
assert.equal(row.shots.length,old.shots.length);
assert.ok(row.progress.maxNoHit<12);
assert.ok(row.shots[10].hits>=old.shots[10].hits);
const hits=r=>r.shots.reduce((n,s)=>n+s.hits,0);
assert.ok(hits(row)>=hits(old));
const before=read('test-results/stage33-independent-baseline.json');
const after=read('test-results/stage33-independent-production.json');
assert.equal(after.summary.naturallyConcluded,96);
const independentChanges=after.rows.flatMap((row,i)=>JSON.stringify(row)===JSON.stringify(before.rows[i])?[]:[{index:i,before:before.rows[i],after:row}]);
const data={fixed:{summary:production.summary,identical:359,changed},independent:{summary:after.summary,identical:96-independentChanges.length,changes:independentChanges}};
writeFileSync('test-results/stage33-final-comparison.json',JSON.stringify(data,null,2)+'\n');
console.log(JSON.stringify({fixed:production.summary,changed:[index],independent:after.summary,independentChanges:independentChanges.map(x=>[x.index,x.after.seed,x.after.material,x.after.size,x.after.policy,x.before.progress.maxNoHit,x.after.progress.maxNoHit,hits(x.before),hits(x.after)])}));
